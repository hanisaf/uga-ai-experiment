import argparse
import os
from pathlib import Path
from PIL import Image

# ==============================================================================
# DEFAULT PARAMETERS / CONFIGURATION VARIABLES
# You can modify these values directly in the script or pass command-line options.
# ==============================================================================

# Directory paths
INPUT_DIR = "."
OUTPUT_DIR = "."

# Input file pattern
INPUT_EXTENSION = "*.png"

# Crop percentages (0.10 = 10% crop from each edge)
CROP_PERCENT_TOP = 0.10
CROP_PERCENT_BOTTOM = 0.10
CROP_PERCENT_LEFT = 0.10
CROP_PERCENT_RIGHT = 0.10

# Output filename formatting variables
# Default output pattern: {PREFIX}{n}{LEFT_SUFFIX}{OUTPUT_EXT}
# Example: s01_passport.jpg (or s1_passport.jpg if STRIP_LEADING_ZEROS is True)
PREFIX = "s"
LEFT_SUFFIX = "_passport"
RIGHT_SUFFIX = "_counter"
OUTPUT_EXT = ".jpg"

# If True, '01' becomes '1' -> 's1_passport.jpg'. If False, keeps '01' -> 's01_passport.jpg'
STRIP_LEADING_ZEROS = False

# Output JPEG quality (1-100)
JPEG_QUALITY = 95


def process_image(
    image_path: Path,
    output_dir: Path,
    crop_top: float = CROP_PERCENT_TOP,
    crop_bottom: float = CROP_PERCENT_BOTTOM,
    crop_left: float = CROP_PERCENT_LEFT,
    crop_right: float = CROP_PERCENT_RIGHT,
    prefix: str = PREFIX,
    left_suffix: str = LEFT_SUFFIX,
    right_suffix: str = RIGHT_SUFFIX,
    output_ext: str = OUTPUT_EXT,
    strip_zeros: bool = STRIP_LEADING_ZEROS,
    jpeg_quality: int = JPEG_QUALITY,
):
    """
    1. Splits the image vertically into left and right halves.
    2. Crops specified percentage margins from each edge of both halves.
    3. Saves the left half as {PREFIX}{n}{LEFT_SUFFIX}{OUTPUT_EXT}
       and the right half as {PREFIX}{n}{RIGHT_SUFFIX}{OUTPUT_EXT}.
    """
    stem = image_path.stem
    if strip_zeros:
        try:
            n = str(int(stem))
        except ValueError:
            n = stem
    else:
        n = stem

    with Image.open(image_path) as img:
        width, height = img.size
        mid_x = width // 2

        # Step 1: Split vertically in half
        left_half = img.crop((0, 0, mid_x, height))
        right_half = img.crop((mid_x, 0, width, height))

        # Helper function to crop specified margins from sub-image
        def crop_sub_image(sub_img):
            w, h = sub_img.size
            l_px = int(w * crop_left)
            t_px = int(h * crop_top)
            r_px = w - int(w * crop_right)
            b_px = h - int(h * crop_bottom)
            return sub_img.crop((l_px, t_px, r_px, b_px))

        # Step 2: Crop 10% (or configured percentage) from each direction
        passport_img = crop_sub_image(left_half)
        counter_img = crop_sub_image(right_half)

        # Convert RGBA/Palette images to RGB mode for JPEG format compatibility
        if output_ext.lower() in [".jpg", ".jpeg"]:
            if passport_img.mode in ("RGBA", "LA", "P"):
                passport_img = passport_img.convert("RGB")
            if counter_img.mode in ("RGBA", "LA", "P"):
                counter_img = counter_img.convert("RGB")

        # Step 3: Define file names and save
        passport_filename = f"{prefix}{n}{left_suffix}{output_ext}"
        counter_filename = f"{prefix}{n}{right_suffix}{output_ext}"

        passport_path = output_dir / passport_filename
        counter_path = output_dir / counter_filename

        passport_img.save(passport_path, quality=jpeg_quality)
        counter_img.save(counter_path, quality=jpeg_quality)

        return passport_filename, counter_filename, passport_img.size


def main():
    parser = argparse.ArgumentParser(
        description="Split PNG images vertically and crop margins from each direction."
    )
    parser.add_argument("--input-dir", type=str, default=INPUT_DIR, help="Input directory path")
    parser.add_argument("--output-dir", type=str, default=OUTPUT_DIR, help="Output directory path")
    parser.add_argument("--crop", type=float, default=CROP_PERCENT_TOP, help="Crop percentage for all sides (e.g., 0.10)")
    parser.add_argument("--strip-zeros", action="store_true", default=STRIP_LEADING_ZEROS, help="Strip leading zeros from numeric filenames")
    
    args = parser.parse_args()

    input_path = Path(args.input_dir)
    output_path = Path(args.output_dir)
    output_path.mkdir(parents=True, exist_ok=True)

    # Gather matching images
    png_files = sorted(list(input_path.glob(INPUT_EXTENSION)))

    if not png_files:
        print(f"No files matching '{INPUT_EXTENSION}' found in '{input_path.resolve()}'.")
        return

    print(f"Processing {len(png_files)} image(s) from '{input_path.resolve()}'...\n")

    for file_path in png_files:
        # Ignore files generated by this script if they happen to match pattern
        if file_path.name.startswith(PREFIX) and (LEFT_SUFFIX in file_path.name or RIGHT_SUFFIX in file_path.name):
            continue

        passport_fn, counter_fn, size = process_image(
            file_path,
            output_path,
            crop_top=args.crop,
            crop_bottom=args.crop,
            crop_left=args.crop,
            crop_right=args.crop,
            strip_zeros=args.strip_zeros,
        )
        print(f"Processed '{file_path.name}':")
        print(f"  ├── Passport: {passport_fn} ({size[0]}x{size[1]} px)")
        print(f"  └── Counter:  {counter_fn} ({size[0]}x{size[1]} px)")

    print(f"\nCompleted! Processed {len(png_files)} images.")


if __name__ == "__main__":
    main()
